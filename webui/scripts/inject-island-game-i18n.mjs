for (const [name, obj] of Object.entries(translations)) {
  const file = join(localesDir, `${name}.json`)
  let text = readFileSync(file, 'utf8')
  if (text.includes('"islandGame"')) {
    console.log(`skip ${name} (already has islandGame)`)
    continue
  }
  const block = JSON.stringify(obj, null, 2).split('\n').join('\n  ')
  // Insert right after the opening brace: { \n  "islandGame": {...},
  text = text.replace(/^\{\r?\n/, `{\n  "islandGame": ${block},\n`)
  writeFileSync(file, text, 'utf8')
  console.log(`injected islandGame into ${name}.json`)
}
