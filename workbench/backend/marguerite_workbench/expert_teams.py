def A(
    role: str,
    team: str,
    title: str,
    kind: str,
    distilled_from: list[str],
    template: str,
    skills: list[tuple],
    notes: str,
    signals: list[tuple],
    recommendations: list[str],
    pass_at: int = 4,
    cond_at: int = 2,
    conf_base: float = 0.4,
    conf_step: float = 0.12,
) -> dict:
    """Build one role spec. ``A`` = *agent*; keeps the catalogue readable."""
    return {
        "role": role,
        "team": team,
        "title": title,
        "kind": kind,
        "distilled_from": list(distilled_from),
        "template": template,
        "skills": [
            {"name": n, "description": d, "procedure": list(p)} for n, d, p in skills
        ],
        "notes": notes,
        "signals": [(n, tuple(k)) for n, k in signals],
        "recommendations": list(recommendations),
        "pass_at": pass_at,
        "cond_at": cond_at,
        "conf_base": conf_base,
        "conf_step": conf_step,
    }


def _blob(payload: dict) -> str:
    """Flatten a payload dict into one lower-cased text blob for keyword probes."""
    parts: list[str] = []
    for key, value in payload.items():
        parts.append(str(key))
        if isinstance(value, (list, tuple)):
            parts.extend(str(v) for v in value)
        else:
            parts.append(str(value))
    return "\n".join(parts).lower()


def analyze_team_role(spec: dict, payload: dict) -> ExpertAnalysis:
    """Run a catalogue role's domain checklist against ``payload``."""
    if not isinstance(payload, dict):
        raise ValueError("payload must be a dict")
    names = [n for n, _ in spec["signals"]]
    present = [n for n, kws in spec["signals"] if any(k in _blob(payload) for k in kws)]
    missing = [n for n in names if n not in present]

    findings: list[str] = []
    if present:
        findings.append(f"已覆盖维度（{len(present)}/{len(names)}）：{'、'.join(present)}")
    if missing:
        findings.append(f"缺失/待补充维度：{'、'.join(missing)}")

    recs = list(spec["recommendations"])
    for m in missing:
        recs.append(f"补充「{m}」相关信息后重新提交分析。")

    score = len(present)
    if score >= spec["pass_at"]:
        verdict = "pass"
    elif score >= spec["cond_at"]:
        verdict = "conditional"
    else:
        verdict = "fail"

    return ExpertAnalysis(
        role=spec["role"],
        verdict=verdict,
        findings=findings,
        recommendations=recs,
        confidence=round(min(1.0, spec["conf_base"] + spec["conf_step"] * score), 2),
    )


